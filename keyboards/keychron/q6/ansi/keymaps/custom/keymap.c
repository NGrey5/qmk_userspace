// clang-format on

// "Backlight off" is represented as LED_FLAG_NONE (effects hidden, indicators
// still drawn) instead of disabling RGB Matrix, because QMK skips the indicator
// hooks entirely when RGB Matrix is disabled. This mirrors Keychron's firmware.
bool process_record_user(uint16_t keycode, keyrecord_t *record) {
    switch (keycode) {
        case RM_TOGG:
        case UG_TOGG:
            if (record->event.pressed) {
                rgb_matrix_set_flags(rgb_matrix_get_flags() == LED_FLAG_NONE ? LED_FLAG_ALL : LED_FLAG_NONE);
            }
            return false;
    }
    return true;
}

// If something else disables RGB Matrix (e.g. Launcher's on/off control),
// convert that into "indicators only" and re-enable it. These calls write to
// EEPROM, but only on the transition, not on every loop.
void housekeeping_task_user(void) {
    if (!rgb_matrix_is_enabled()) {
        rgb_matrix_set_flags(LED_FLAG_NONE);
        rgb_matrix_enable();
    }
    if (rgb_matrix_get_mode() == RGB_MATRIX_NONE) {
        rgb_matrix_mode(RGB_MATRIX_SOLID_COLOR);
    }
}

// Runs after the effect is drawn and before the LEDs are updated, so anything
// written here overrides the effect. Returning false skips Keychron's stock
// indicator code in q6.c.
bool rgb_matrix_indicators_advanced_user(uint8_t led_min, uint8_t led_max) {
    if (rgb_matrix_get_flags() == LED_FLAG_NONE) {
        for (uint8_t i = led_min; i < led_max; i++) {
            rgb_matrix_set_color(i, 0, 0, 0);
        }
    }

    led_t led_state = host_keyboard_led_state();

    if (led_state.caps_lock) {
        RGB_MATRIX_INDICATOR_SET_COLOR(CAPS_LOCK_LED_INDEX, 255, 255, 255);
    }

    // Inverted from stock: lit only when Num Lock is OFF
    if (!led_state.num_lock) {
        RGB_MATRIX_INDICATOR_SET_COLOR(NUM_LOCK_LED_INDEX, 255, 255, 255);
    }

    return false;
}